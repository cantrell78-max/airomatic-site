export function pickCompany(rng, used) {
  const pool = used && used.size ? COMPANIES.filter((c) => !used.has(c.name)) : COMPANIES;
  const src = pool.length ? pool : COMPANIES;
  return src[(rng() * src.length) | 0];
}
